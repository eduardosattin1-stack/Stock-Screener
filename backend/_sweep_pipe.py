MIN_FRESH_RATIO   = 0.6   # compose gate: fresh board must be >= this fraction of the prior board

# The Workflow permission validator rejects non-ASCII in generated .js (it misreads UTF-8 as C1
# controls) — every run before 2026-08-19 hand-folded the files after a failed launch. Fold at
# generation instead: NFKD-strip accents (company-name cosmetics only; tickers are ASCII).
_FOLD = {'\u2014': '-', '\u2013': '-', '\u2018': "'", '\u2019': "'", '\u201c': '"', '\u201d': '"',
         '\u2264': '<=', '\u2265': '>=', '\u00b1': '+/-', '\u2500': '-', '\u2192': '->', '\u00a0': ' '}
def _ascii_fold(s):
    out = []
    for ch in unicodedata.normalize('NFKD', s):
        if ord(ch) < 128:
            out.append(ch)
        else:
            out.append(_FOLD.get(ch, ''))
    return ''.join(out)

def _load_manifest():
    try:
        return json.load(open(MANIFEST_F, encoding='utf-8'))
    except (FileNotFoundError, ValueError):
        return None

def _save_manifest(m):
    json.dump(m, open(MANIFEST_F, 'w', encoding='utf-8'), indent=1)

