#!/usr/bin/env python
# Catalyst sweep loop engine. Modes:
#   python _sweep_pipe.py gen <n>          -> write chunk n's workflow .js (ASCII-folded; n==1 also
#                                             snapshots the board to .bak and starts a fresh run manifest)
#   python _sweep_pipe.py harvest <task_output.json> <n>
#                                          -> extract the Workflow result into chunk<n>.json + register
#                                             it in the run manifest (replaces hand-copying the result)
#   python _sweep_pipe.py compose          -> gate-checked ATOMIC board build from this run's harvested
#                                             chunks. The live board is never blanked mid-run: a failed
#                                             or degraded sweep simply never composes, and the prior
#                                             board stays untouched (kills the 2026-08-18 hazards:
#                                             mid-run [] reset + stale prior-run chunk JSONs).
#   python _sweep_pipe.py inject <chunk_output.json>
#                                          -> legacy per-chunk accumulate (kept for gap-fills)
#   python _sweep_pipe.py genlist <tag> <SYM,SYM,...>
import json, sys, os, unicodedata, datetime

BASE = 'C:/Users/Bruno/Stock-Screener'
