def regen_ts(board):
    raw = json.dumps(board, ensure_ascii=False)
    open(TS_F, 'w', encoding='utf-8').write(TS_TEMPLATE.replace('__SWEEP_RAW__', raw))

def inject(chunk_file):
    uni = {x['symbol']: x for x in json.load(open(UNIVERSE_F, encoding='utf-8'))}
    board = json.load(open(BOARD_F, encoding='utf-8')) if os.path.exists(BOARD_F) else []
    by_sym = {b['symbol']: b for b in board}
    d = json.load(open(chunk_file, encoding='utf-8'))
    res = d.get('result', d)
    label = res.get('chunk', '')
    added = []
    for v in res.get('verified', []):
        tier = v.get('tier'); score = v.get('score') or 0
        if tier in ('ACTIVE', 'WATCH') and score >= 4:
            sym = v['symbol']
            by_sym[sym] = {
                'symbol': sym, 'company_name': uni.get(sym, {}).get('company_name', sym),
                'score': score, 'tier': tier, 'lane': v.get('lane', ''), 'catalyst': v.get('catalyst', ''),
                'dated_milestone': v.get('dated_milestone', ''), 'instrument': v.get('instrument', ''),
                'bloom_gates': v.get('bloom_gates', ''), 'edge': v.get('edge', ''), 'analysis': v.get('analysis', ''),
                'primary_source': v.get('primary_source', ''), 'verdict': v.get('verdict') or '',
                'kill_fact': v.get('kill_fact') or '', 'chunk': label,
            }
            added.append(f"{sym}({score},{tier})")
    board = sorted(by_sym.values(), key=lambda b: -(b.get('score') or 0))
    json.dump(board, open(BOARD_F, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    regen_ts(board)
    print(f"INJECTED {len(added)} from chunk '{label}': {', '.join(added)}")
    print(f"BOARD now {len(board)} sweep names")

def gen(n):
    uni = json.load(open(UNIVERSE_F, encoding='utf-8'))
    chunk = uni[(n-1)*SIZE : n*SIZE]
    if not chunk:
        print(f"NO_MORE_CHUNKS (n={n}, universe={len(uni)})"); return
    if n == 1:
        # a new sweep run: snapshot the live board (compose's gate baseline) and reset the
        # manifest. The board itself is NOT touched — it stays live until compose passes.
        if os.path.exists(BOARD_F):
            prev = json.load(open(BOARD_F, encoding='utf-8'))
            json.dump(prev, open(BAK_F, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
            print(f"SNAPSHOT {len(prev)} names -> _sweep_board.bak.json")
        _save_manifest({'run_date': datetime.date.today().isoformat(),
                        'universe': len(uni), 'expected': [], 'harvested': {}})
        print("MANIFEST reset for a new run")
    m = _load_manifest()
    if m is None:
        print("WARN: no run manifest (gen 1 not run first?) — creating one mid-run")
        m = {'run_date': datetime.date.today().isoformat(), 'universe': len(uni),
             'expected': [], 'harvested': {}}
    if n not in m['expected']:
        m['expected'].append(n); _save_manifest(m)
    names = [{'symbol': x['symbol'], 'company_name': x['company_name']} for x in chunk]
    label = f"{n} ({chunk[0]['symbol']}-{chunk[-1]['symbol']})"
    js = (JS_TEMPLATE.replace('__N__', str(n)).replace('__NAMES__', json.dumps(names, ensure_ascii=False))
          .replace('__LABEL__', label).replace('__TODAY__', datetime.date.today().isoformat()))
    js = _ascii_fold(js)
    out = f'{BASE}/backend/_sweep_results/chunk{n}_workflow.js'
    open(out, 'w', encoding='ascii', newline='\n').write(js)
    print(f"WROTE {out} ({len(names)} names, label '{label}', ASCII-folded)")
    print(out)


def harvest(task_file, n):
    """Extract a Workflow tool's task-output JSON into chunk<n>.json + register in the manifest."""
    d = json.load(open(task_file, encoding='utf-8'))
    res = d.get('result', d)
    if not isinstance(res, dict) or 'verified' not in res:
        print(f"CHUNK {n} FAILED: no usable result object (keys={list(d)[:8]})"); sys.exit(1)
    out = f'{BASE}/backend/_sweep_results/chunk{n}.json'
    json.dump(res, open(out, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    kept = [v for v in res.get('verified', [])
            if v.get('tier') in ('ACTIVE', 'WATCH') and (v.get('score') or 0) >= 4]
    m = _load_manifest()
    if m is None:
        print("WARN: no run manifest — harvest recorded to disk only")
    else:
        m['harvested'][str(n)] = {'scanned': res.get('scanned', 0),
                                  'flagged': len(res.get('survivors_flagged', [])),
                                  'verified': len(res.get('verified', [])), 'kept': len(kept)}
        _save_manifest(m)
    print(f"HARVESTED chunk {n}: scanned={res.get('scanned')} verified={len(res.get('verified', []))} -> {len(kept)} keepable")
    print(f"WROTE {out}")


def compose():
    """Gate-checked atomic board build from THIS run's harvested chunks only."""
    m = _load_manifest()
    if m is None:
        print("ABORT: no run manifest — nothing to compose (run gen 1 first)"); sys.exit(1)
    expected  = sorted(m.get('expected', []))
    harvested = sorted(int(k) for k in m.get('harvested', {}))
    failed = [n for n in expected if n not in harvested]
    if len(failed) > MAX_FAILED_CHUNKS:
        print(f"ABORT: {len(failed)} chunks un-harvested {failed} (limit {MAX_FAILED_CHUNKS}) — "
              "prior board left untouched"); sys.exit(1)
    uni = {x['symbol']: x for x in json.load(open(UNIVERSE_F, encoding='utf-8'))}
    by = {}
    for n in harvested:
        res = json.load(open(f'{BASE}/backend/_sweep_results/chunk{n}.json', encoding='utf-8'))
        label = res.get('chunk', str(n))
        for v in res.get('verified', []):
            if v.get('tier') in ('ACTIVE', 'WATCH') and (v.get('score') or 0) >= 4:
                s = v['symbol']
                by[s] = {'symbol': s, 'company_name': uni.get(s, {}).get('company_name', s),
                         'score': v.get('score'), 'tier': v.get('tier'), 'lane': v.get('lane', ''),
                         'catalyst': v.get('catalyst', ''), 'dated_milestone': v.get('dated_milestone', ''),
                         'instrument': v.get('instrument', ''), 'bloom_gates': v.get('bloom_gates', ''),
                         'edge': v.get('edge', ''), 'analysis': v.get('analysis', ''),
                         'primary_source': v.get('primary_source', ''), 'verdict': v.get('verdict') or '',
                         'kill_fact': v.get('kill_fact') or '', 'chunk': label}
    prev_n = 0
    if os.path.exists(BAK_F):
        prev_n = len(json.load(open(BAK_F, encoding='utf-8')))
    if prev_n and len(by) < MIN_FRESH_RATIO * prev_n:
        print(f"ABORT: fresh board {len(by)} < {MIN_FRESH_RATIO} x prev {prev_n} = "
              f"{MIN_FRESH_RATIO*prev_n:.0f} — sweep materially degraded, prior board left untouched")
        sys.exit(1)
    board = sorted(by.values(), key=lambda b: -(b.get('score') or 0))
    tmp = BOARD_F + '.tmp'
    json.dump(board, open(tmp, 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    os.replace(tmp, BOARD_F)           # atomic: the live board is never half-written
    regen_ts(board)
    old = {x['symbol'] for x in json.load(open(BAK_F, encoding='utf-8'))} if prev_n else set()
    new = set(by)
    print(f"COMPOSED board: {len(board)} names ({prev_n} before) | chunks {len(harvested)}/{len(expected)}"
          f"{' | FAILED: ' + str(failed) if failed else ''}")
    print(f"  entered ({len(new-old)}): {' '.join(sorted(new-old)) or '-'}")
    print(f"  dropped ({len(old-new)}): {' '.join(sorted(old-new)) or '-'}")

def genlist(tag, syms):
    # gap-fill: build a workflow for an arbitrary ticker list (rate-limit losses, remaps, ad-hoc).
    uni = {x['symbol']: x for x in json.load(open(UNIVERSE_F, encoding='utf-8'))}
    miss = [s for s in syms if s not in uni]
    if miss: print(f"WARN not in universe (skipped): {miss}")
    syms = [s for s in syms if s in uni]
    names = [{'symbol': s, 'company_name': uni[s]['company_name']} for s in syms]
    label = f"gapfill-{tag} ({len(names)} names)"
    js = (JS_TEMPLATE.replace('__N__', tag).replace('__NAMES__', json.dumps(names, ensure_ascii=False))
          .replace('__LABEL__', label).replace('__TODAY__', datetime.date.today().isoformat()))
    js = _ascii_fold(js)
    out = f'{BASE}/backend/_sweep_results/gapfill_{tag}_workflow.js'
    open(out, 'w', encoding='ascii', newline='\n').write(js)
    print(f"WROTE {out} ({len(names)} names: {[n['symbol'] for n in names]}, label '{label}', ASCII-folded)")
    print(out)

if __name__ == '__main__':
    mode = sys.argv[1]
    if mode == 'inject': inject(sys.argv[2])
    elif mode == 'gen': gen(int(sys.argv[2]))
    elif mode == 'harvest': harvest(sys.argv[2], int(sys.argv[3]))
    elif mode == 'compose': compose()
    elif mode == 'genlist': genlist(sys.argv[2], [s.strip().upper() for s in sys.argv[3].split(',') if s.strip()])
    else: print(f"unknown mode '{mode}' (gen | harvest | compose | inject | genlist)"); sys.exit(2)
